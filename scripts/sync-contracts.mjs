import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const appDir = resolve(scriptDir, "..");
const repoDir = resolve(appDir, "../..");
const deploymentsDir = resolve(repoDir, "packages/contracts/deployments");
const outputFile = resolve(appDir, "src/contracts/registry.ts");

const deploymentFiles = (await readdir(deploymentsDir)).filter((file) => /^\d+\.json$/.test(file)).sort();
if (deploymentFiles.length === 0) throw new Error(`No chain deployment manifests found under ${deploymentsDir}`);

const deploymentMetadata = {};
const contractsByChainId = {};

for (const file of deploymentFiles) {
  const manifest = JSON.parse(await readFile(resolve(deploymentsDir, file), "utf8"));
  const chainId = Number(manifest.chainId);
  const network = manifest.network;
  if (!Number.isSafeInteger(chainId) || !network) continue;

  const networkDir = resolve(deploymentsDir, network);
  const artifacts = (await readdir(networkDir)).filter((name) => name.endsWith(".json")).sort();
  const networkContracts = {};

  for (const artifactName of artifacts) {
    const name = artifactName.slice(0, -".json".length);
    const artifact = JSON.parse(await readFile(resolve(networkDir, artifactName), "utf8"));
    if (!Array.isArray(artifact.abi)) continue;

    const contract = { abi: artifact.abi };
    if (typeof artifact.address === "string" && /^0x[\da-fA-F]{40}$/.test(artifact.address)) {
      contract.address = artifact.address;
    }
    networkContracts[name] = contract;
  }

  if (Object.keys(networkContracts).length === 0) continue;
  deploymentMetadata[chainId] = {
    network,
    chainId,
    timestamp: manifest.timestamp,
    deployer: manifest.deployer,
    owner: manifest.owner,
    config: manifest.config ?? {},
  };
  contractsByChainId[chainId] = networkContracts;
}

const generated = `/* eslint-disable */\n/**\n * Generated by scripts/sync-contracts.mjs from packages/contracts/deployments.\n * Do not edit manually; run \`pnpm contracts:sync\` from apps/dapp.\n */\n\nimport type { GenericContractsDeclaration } from "./types";\n\nexport const deploymentMetadataByChainId = ${JSON.stringify(deploymentMetadata, null, 2)} as const;\n\nexport const contractsByChainId = ${JSON.stringify(contractsByChainId, null, 2)} as const satisfies GenericContractsDeclaration;\n`;

await writeFile(outputFile, generated);
console.log(`Wrote ${outputFile} for ${Object.keys(contractsByChainId).length} network(s).`);
